package com.adyen.commerce.connector.dto;

/** When a cancellation takes effect. No default: every call site names its timing. */
public enum CancellationTiming
{
	/** Stop renewing; keep serving until the paid period runs out. */
	AT_PERIOD_END,

	/**
	 * End now, forfeiting the rest of the paid period (a Recurly <em>terminate</em>). No refund instruction is
	 * sent, so the platform account's own settings decide what happens to the money.
	 */
	IMMEDIATELY
}
