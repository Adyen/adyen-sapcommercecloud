package com.adyen.commerce.connector.facades.data;

/**
 * What the shopper is warned about before going to the platform's own payment-method page. The page builds
 * its message key from the name, so these names are part of the message contract.
 */
public enum PaymentMethodEnrollmentNotice
{
	/** The new method joins what the platform holds. */
	ADDS_METHOD,
	/** The new method takes the place of the one the platform holds for the account. */
	REPLACES_METHOD_ON_FILE
}
